// Builds game/solo-sw-files.js: every file solo mode needs offline, for the service worker
// to save on install. Run after adding game files:  node tools/solo/precache.mjs
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const ROOT = new URL('../../', import.meta.url);
const DIRS = ['game/world3d', 'game/sea3d', 'game/lib', 'game/assets', 'game/assets3d', 'game/world/assets'];
const FILES = ['game/items.js', 'game/sprite.js', 'game/index.html'];
const PAGES = ['/game/', '/game/world3d/', '/game/sea3d/']; // pages as their address, besides their index.html
const SKIP = /\.(md|py|blend|blend1)$/;
const THREE = 'https://cdn.jsdelivr.net/npm/three@0.160.0/';
const OTHER_CDN = ['https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.49.1/dist/umd/supabase.min.js'];

export function localFiles() {
  const tracked = execSync(`git ls-files ${DIRS.join(' ')} ${FILES.join(' ')}`, { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);
  return [...PAGES, ...tracked.filter((f) => !SKIP.test(f)).map((f) => '/' + f)].sort();
}

// three's addons import each other by relative path: follow them all
async function cdnFiles(local) {
  const entry = new Set(['build/three.module.js']); // plus every 'three/addons/...' the game imports
  for (const f of local.filter((f) => /\.(js|html)$/.test(f))) {
    const src = readFileSync(new URL('.' + f, ROOT), 'utf8');
    for (const [, p] of src.matchAll(/['"]three\/addons\/([^'"]+)['"]/g)) entry.add('examples/jsm/' + p);
  }
  const seen = new Set(), todo = [...entry].map((p) => THREE + p);
  while (todo.length) {
    const url = todo.pop();
    if (seen.has(url)) continue;
    seen.add(url);
    const src = await (await fetch(url)).text();
    for (const [, spec] of src.matchAll(/(?:import|export)[^'"]*?from\s*['"]([^'"]+)['"]/g)) {
      if (spec === 'three') continue;
      todo.push(new URL(spec, url).href);
    }
  }
  return [...seen, ...OTHER_CDN].sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const local = localFiles();
  const files = [...local, ...(await cdnFiles(local.filter((f) => !PAGES.includes(f))))];
  const version = createHash('sha1').update(files.join('\n')).digest('hex').slice(0, 10);
  writeFileSync(new URL('game/solo-sw-files.js', ROOT),
    `// generated by tools/solo/precache.mjs — do not edit\nself.SOLO_VERSION = '${version}';\nself.SOLO_FILES = ${JSON.stringify(files, null, 1)};\n`);
  console.log(`${files.length} files, version ${version}`);
}
